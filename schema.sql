-- Esquema base para el sistema de RH en Supabase.
-- Ejecuta este archivo en el SQL Editor de Supabase y ajusta las políticas RLS
-- a los roles de tu proyecto.

create table if not exists departamentos (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text,
  activo boolean not null default true
);

create table if not exists puestos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  salario_base numeric(12,2) not null default 0,
  departamento_id bigint references departamentos(id),
  activo boolean not null default true
);

create table if not exists empleados (
  id bigint generated by default as identity primary key,
  numero_empleado text not null unique,
  nombre text not null,
  apellido text not null,
  email text unique,
  fecha_ingreso date not null default current_date,
  puesto_id bigint references puestos(id),
  departamento_id bigint references departamentos(id),
  activo boolean not null default true
);

create table if not exists nomina (
  id bigint generated by default as identity primary key,
  empleado_id bigint not null references empleados(id),
  periodo_inicio date not null,
  periodo_fin date not null,
  salario_bruto numeric(12,2) not null,
  deducciones numeric(12,2) not null default 0,
  salario_neto numeric(12,2) generated always as (salario_bruto - deducciones) stored,
  pagada boolean not null default false
);

create table if not exists vacaciones (
  id bigint generated by default as identity primary key,
  empleado_id bigint not null references empleados(id),
  fecha_inicio date not null,
  fecha_fin date not null,
  dias integer not null check (dias > 0),
  estado text not null default 'pendiente'
    check (estado in ('pendiente', 'aprobada', 'rechazada'))
);

create table if not exists asistencias (
  id bigint generated by default as identity primary key,
  empleado_id bigint not null references empleados(id),
  fecha date not null,
  hora_entrada time,
  hora_salida time,
  estado text not null default 'presente'
    check (estado in ('presente', 'retardo', 'falta', 'permiso')),
  unique (empleado_id, fecha)
);
